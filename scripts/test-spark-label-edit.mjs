import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const src=readFileSync('vip-access/spark/manager.mjs','utf8');
const start=src.indexOf('function normalizeVipLabel(value){');
const end=src.indexOf('\n}',start)+2;
assert(start>=0&&end>start);
const snippet=src.slice(start,end);
const normalize=vm.runInNewContext('('+snippet+')');
assert.equal(normalize(' 王小姐 '),'王小姐');
assert.equal(normalize('  業務A-1  '),'業務A-1');
for(const value of ['', ' ', 'X'.repeat(81), null, 101])assert.throws(()=>normalize(value));
assert(src.includes("readFirebaseRest('whitelist/'+encodeURIComponent(code))"));
assert(src.includes("await withDeadline(set(ref(db,'vipProfiles/'+code),updatedLabel),15000,'label')"));
assert(src.includes("readFirebaseRest('vipProfiles/'+encodeURIComponent(code))!==updatedLabel"));
assert(src.includes("nameText.textContent=updatedLabel"));
assert(src.includes("accountRows=newRows"));
assert(src.includes("el('accountFilter').addEventListener('input',applyAccountFilter)"));
assert(src.includes("nextVipStatus(current,enabled)"));
assert(src.includes('await withDeadline(remove(ref(db,\'whitelist/\'+code))'));
assert(!src.includes('localStorage.clear('));
const html=readFileSync('vip-access/spark/manager.html','utf8');
assert(html.includes('id="accountFilter"'));
assert(html.includes('修改標籤'));
console.log('Spark VIP label edit, search and retention regression: PASS');
